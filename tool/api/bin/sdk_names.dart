/// Writes `tool/structure/sdk_names.txt`: the public type names of each
/// library a flutter3d user imports beside ours, by following the library's
/// export clauses (`show` and `hide` included) through the Flutter SDK, the
/// Dart SDK under it and the pub cache.
///
///     dart run api_snapshot:sdk_names            print it
///     dart run api_snapshot:sdk_names --update   write it
///
/// Regenerate it when the Flutter floor in SUPPORT.md moves: a newer SDK adds
/// names, and a name it adds that one of ours already has is a collision the
/// rule should see.
library;

import 'dart:convert';
import 'dart:io';

import 'package:analyzer/dart/analysis/utilities.dart';
import 'package:analyzer/dart/ast/ast.dart';
import 'package:api_snapshot/api_snapshot.dart';

/// The libraries listed, in order. The rule `no public name collides with
/// Flutter, Dart or vector_math` reads every one; the rule `a signature names
/// only types a caller can import` reads them as the names that are nobody's
/// third-party dependency.
const List<String> libraries = <String>[
  'package:flutter/material.dart',
  'package:flutter/foundation.dart',
  'package:flutter/services.dart',
  'package:flutter/rendering.dart',
  'package:flutter/scheduler.dart',
  'package:flutter/gestures.dart',
  'package:flutter/physics.dart',
  'dart:core',
  'dart:async',
  'dart:ui',
  'dart:io',
  'dart:typed_data',
  'dart:math',
  'dart:collection',
  'dart:convert',
  'dart:isolate',
  'dart:ffi',
  'dart:developer',
  'dart:js_interop',
  'package:vector_math/vector_math.dart',
  'package:vector_math/vector_math_64.dart',
  'package:meta/meta.dart',
];

void main(List<String> args) {
  final root = repositoryRootFrom(Directory.current);
  final flutter = _flutterRoot();
  final packages = _packageRoots(root);
  final out = StringBuffer()
    ..writeln(
      '# The public type names of the libraries a flutter3d user imports beside',
    )
    ..writeln(
      '# ours, read by the rules `no public name collides with Flutter, Dart or',
    )
    ..writeln(
      '# vector_math` and `a signature names only types a caller can import`',
    )
    ..writeln('# (tool/structure/naming.dart).')
    ..writeln('#')
    ..writeln(
      '# Generated by `dart run api_snapshot:sdk_names --update` in tool/api',
    )
    ..writeln(
      '# from Flutter ${_flutterVersion(flutter)} by following each library\'s',
    )
    ..writeln(
      '# export clauses (show and hide included); a newer SDK adds names, so',
    )
    ..writeln('# regenerate it when the floor in SUPPORT.md moves.');
  for (final library in libraries) {
    final file = _resolve(library, null, flutter, packages);
    if (file == null) {
      stderr.writeln('cannot find $library');
      exit(1);
    }
    final names = _exported(file, flutter, packages, <String>{}).toList()
      ..sort();
    out
      ..writeln()
      ..writeln('[$library]');
    for (final name in names) {
      out.writeln(name);
    }
  }
  if (args.contains('--update')) {
    File(
      '${root.path}/tool/structure/sdk_names.txt',
    ).writeAsStringSync(out.toString());
  } else {
    stdout.write(out);
  }
}

Directory _flutterRoot() {
  final dart = File(Platform.resolvedExecutable).resolveSymbolicLinksSync();
  // <flutter>/bin/cache/dart-sdk/bin/dart
  return File(dart).parent.parent.parent.parent.parent;
}

String _flutterVersion(Directory flutter) {
  final version = File('${flutter.path}/bin/cache/flutter.version.json');
  if (!version.existsSync()) return 'the SDK on the path';
  final json = jsonDecode(version.readAsStringSync()) as Map<String, Object?>;
  return '${json['frameworkVersion'] ?? json['flutterVersion']}';
}

Map<String, Directory> _packageRoots(Directory root) {
  final config = File('${root.path}/.dart_tool/package_config.json');
  final json = jsonDecode(config.readAsStringSync()) as Map<String, Object?>;
  return <String, Directory>{
    for (final p
        in (json['packages']! as List<Object?>).cast<Map<String, Object?>>())
      p['name']! as String: Directory(
        Uri.parse('${config.parent.uri}')
            .resolve(
              '${(p['rootUri']! as String).replaceAll(RegExp(r'/$'), '')}/',
            )
            .resolve('lib/')
            .toFilePath(),
      ),
  };
}

File? _resolve(
  String uri,
  File? from,
  Directory flutter,
  Map<String, Directory> packages,
) {
  if (uri.startsWith('dart:')) {
    final name = uri.substring(5);
    if (name == 'ui') {
      return File('${flutter.path}/bin/cache/pkg/sky_engine/lib/ui/ui.dart');
    }
    final sdk = '${flutter.path}/bin/cache/dart-sdk/lib';
    return File('$sdk/$name/$name.dart');
  }
  if (uri.startsWith('package:')) {
    final segments = uri.substring(8).split('/');
    final lib = segments.first == 'flutter'
        ? Directory('${flutter.path}/packages/flutter/lib/')
        : packages[segments.first];
    if (lib == null) return null;
    return File('${lib.path}${segments.skip(1).join('/')}');
  }
  if (from == null) return null;
  return File(from.parent.uri.resolve(uri).toFilePath());
}

/// The public type names [file] exports: its own and its parts', and what its
/// exports admit.
Set<String> _exported(
  File file,
  Directory flutter,
  Map<String, Directory> packages,
  Set<String> visiting,
) {
  final key = file.absolute.path;
  if (_exportedBy[key] case final known?) return known;
  if (!visiting.add(key) || !file.existsSync()) return <String>{};
  final unit = parseString(
    content: file.readAsStringSync(),
    path: file.absolute.path,
    throwIfDiagnostics: false,
  ).unit;
  final out = <String>{..._declared(unit)};
  for (final part in unit.directives.whereType<PartDirective>()) {
    final uri = part.uri.stringValue;
    if (uri == null) continue;
    final partFile = File(file.parent.uri.resolve(uri).toFilePath());
    if (!partFile.existsSync()) continue;
    out.addAll(
      _declared(
        parseString(
          content: partFile.readAsStringSync(),
          path: partFile.absolute.path,
          throwIfDiagnostics: false,
        ).unit,
      ),
    );
  }
  for (final export in unit.directives.whereType<ExportDirective>()) {
    final uri = export.uri.stringValue;
    if (uri == null) continue;
    final target = _resolve(uri, file, flutter, packages);
    if (target == null) continue;
    var names = _exported(target, flutter, packages, visiting);
    for (final c in export.combinators) {
      names = switch (c) {
        ShowCombinator(:final shownNames) => names.intersection(<String>{
          for (final n in shownNames) n.name,
        }),
        HideCombinator(:final hiddenNames) => names.difference(<String>{
          for (final n in hiddenNames) n.name,
        }),
      };
    }
    out.addAll(names);
  }
  visiting.remove(key);
  return _exportedBy[key] = out;
}

/// What each file exports, once read: the SDK's export graph shares most of
/// its libraries many times over.
final Map<String, Set<String>> _exportedBy = <String, Set<String>>{};

Set<String> _declared(CompilationUnit unit) => <String>{
  for (final d in unit.declarations)
    if (switch (d) {
          ClassDeclaration(:final namePart) => namePart.typeName.lexeme,
          EnumDeclaration(:final namePart) => namePart.typeName.lexeme,
          ExtensionTypeDeclaration(:final namePart) => namePart.typeName.lexeme,
          MixinDeclaration(:final name) => name.lexeme,
          ClassTypeAlias(:final name) => name.lexeme,
          GenericTypeAlias(:final name) => name.lexeme,
          FunctionTypeAlias(:final name) => name.lexeme,
          _ => null,
        }
        case final name? when !name.startsWith('_'))
      name,
};
