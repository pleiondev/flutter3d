/// Writes the public API of every package published at a release tag, as
/// `api/<package>.api` would have held it then — the baseline a migration
/// table is measured against.
///
/// ```
/// cd tool/api
/// dart run api_snapshot:api_baseline v0.8.5 \
///     ../../packages/flutter3d_build/migrations/baseline/0.8.5
/// ```
///
/// **Why a generator and not `git show`.** The snapshots arrived with 1.0.0;
/// the last published release, 0.8.5, has none, so there is nothing at its
/// tag to read. This extracts the tag with `git archive` (which changes
/// nothing in the working tree) into a temporary directory and runs the same
/// [ApiSnapshotter] over it, so the baseline is what the snapshot tool would
/// have written on the day of the release. The result is committed beside the
/// migration table: the structure rule that holds every break to a migration
/// entry runs before `pub get`, and reads text.
///
/// One file per package published at the tag, plus `versions.txt` with each
/// one's version, since a package's own number is what a user's pubspec
/// names.
library;

import 'dart:io';

import 'package:api_snapshot/api_snapshot.dart';

const String _usage = '''
Writes the API of every package published at a tag.

  dart run api_snapshot:api_baseline <tag> <out dir>
''';

Future<void> main(List<String> args) async {
  if (args.length != 2 || args.contains('--help')) {
    stderr.write(_usage);
    exitCode = 2;
    return;
  }
  final tag = args[0];
  final out = Directory(args[1])..createSync(recursive: true);
  final root = repositoryRootFrom(Directory.current);
  final scratch = Directory.systemTemp.createTempSync('api_baseline_');
  try {
    final archive = await Process.start('git', <String>[
      'archive',
      tag,
      'packages',
    ], workingDirectory: root.path);
    final untar = await Process.start('tar', <String>[
      '-x',
      '-C',
      scratch.path,
    ]);
    await archive.stdout.pipe(untar.stdin);
    final archived = await archive.exitCode;
    final extracted = await untar.exitCode;
    if (archived != 0 || extracted != 0) {
      stderr.writeln('could not extract $tag: ${await _text(archive.stderr)}');
      exitCode = 1;
      return;
    }
    final packages = repositoryPackages(scratch);
    final published =
        packages.keys.where((String n) => isPublished(packages[n]!)).toList()
          ..sort();
    final snapshotter = ApiSnapshotter(packages);
    final versions = StringBuffer()
      ..writeln('# The version of each package published at $tag.')
      ..writeln('# Generated by `dart run api_snapshot:api_baseline`.');
    for (final name in published) {
      final text = snapshotter
          .snapshot(name)
          .replaceFirst(
            RegExp(r'^# Generated by .*$', multiLine: true),
            '# Generated from $tag by `dart run api_snapshot:api_baseline` '
            'in tool/api. Do not edit.',
          );
      File('${out.path}/$name.api').writeAsStringSync(text);
      final version = RegExp(r'^version:\s*(\S+)', multiLine: true)
          .firstMatch(
            File('${packages[name]!.path}/pubspec.yaml').readAsStringSync(),
          )
          ?.group(1);
      versions.writeln('$name $version');
    }
    File('${out.path}/versions.txt').writeAsStringSync(versions.toString());
    stdout.writeln(
      'wrote ${published.length} snapshots of $tag to ${out.path}',
    );
  } finally {
    scratch.deleteSync(recursive: true);
  }
}

Future<String> _text(Stream<List<int>> bytes) =>
    bytes.transform(const SystemEncoding().decoder).join();
