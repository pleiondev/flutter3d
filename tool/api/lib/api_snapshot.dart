/// The public surface of a package as text: what `api/<package>.api` holds.
///
/// **What is listed.** Every library a caller can import — each `.dart` file
/// under `lib/` outside `lib/src/` — and in it every name it exports, after
/// `show` and `hide`, through any chain of exports:
///
///  * a declaration of the package itself, in full: its header with its
///    class modifiers, and each public member's signature — types, parameter
///    names, defaults, `const` initialisers (a constant's value is part of
///    what a caller compiled against);
///  * the annotations that change what a caller may do: `@Deprecated` with
///    its message, `@visibleForTesting`, `@protected`, `@internal`,
///    `@experimental` and the rest of [_annotationsThatMatter];
///  * `abstract ` before a member with no body, in a type outside code may
///    extend or mix in — the one place a body decides whether a new member
///    breaks somebody;
///  * a re-export of another package of this repository as its own block,
///    naming the library it comes through and every name it admits, with
///    `from <package>` on a name declared one package further. A
///    whole-library re-export is visible as one: `(whole library)`;
///  * a re-export from outside the repository as one line with its
///    combinators, since its names are somebody else's to list.
///
/// Bodies, doc comments, comments and private members are not listed, and
/// whitespace is normalised, so reformatting or rewording moves nothing.
/// Declarations and members are sorted, so reordering moves nothing either.
/// Parsed, not resolved: the text is what the source says.
library;

