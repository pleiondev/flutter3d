// depends on one by name; there are three today — `flutter3d_impeller`,
// `flutter3d_webgl` and `flutter3d_cpu` — and room for more.
// That choice is the one thing that must stay visible in an application's
// pubspec.
//
// Named, like the core above: the HAL types this package's API and its users'
// code are written in. The registries a backend fills in, the format tables
// and the shader-library plumbing stay `flutter3d_hardware`'s.
