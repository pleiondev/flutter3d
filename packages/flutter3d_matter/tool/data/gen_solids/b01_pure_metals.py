T6 = [100, 200, 300, 400, 600, 800, 1000]
TH = 'thermal.conductivity'
CP = 'thermal.specificHeat'


def kcp(k, cp, xs=T6, note=None):
    out = [table(TH, 'INC', xs, k), table(CP, 'INC', xs, cp)]
    if note:
        for o in out:
            o['note'] = note
    return out


def jc(A, B, n, C, m, Tm, label):
    return {'model': 'johnsonCook',
            'A': P(A * 1e6, 'JC83', ver='recalled'),
            'B': P(B * 1e6, 'JC83', ver='recalled'),
            'n': P(n, 'JC83', ver='recalled'), 'C': P(C, 'JC83', ver='recalled'),
            'm': P(m, 'JC83', ver='recalled'),
            'meltTemperature': P(Tm, 'JC83', ver='recalled'),
            'referenceStrainRate': 1.0, 'roomTemperature': 294.0,
            'note': f'sigma = (A + B eps^n)(1 + C ln(epsdot/1 s^-1))(1 - T*^m); fitted to {label}'}


def mrgb(rgb, src='PBI', ver='fetched', note=None):
    return P(list(rgb), src, ver=ver, note=note)


