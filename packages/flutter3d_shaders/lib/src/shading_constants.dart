/// The numbers the engine's shading takes from physics, each written once:
/// in Dart here, for the software backend and the converters, and in the
/// GLSL every hardware stage includes, `shaders/lib/shading_constants.glsl`,
/// which `tool/gen_shading_constants.dart` writes from this file.
library;

/// A dielectric's reflectance at normal incidence, F0, when a material says
/// nothing else: 0.04, four percent head-on.
///
/// ((n − 1) / (n + 1))² at n = 1.5, the index glTF's metallic–roughness
/// model assumes for every non-metal and `KHR_materials_ior` defaults to,
/// and the formula `flutter3d_matter`'s optical group gives a material's own
/// F0 by (`OpticalProperties.f0`). A clear coat is a dielectric of the same
/// index and reflects the same. No unit.
///
/// Read by the GLSL stages (as `kDielectricF0`), the software backend's
/// shading and the MaterialX converter's programs; a material bound to a
/// catalog entry with an optical group takes that entry's own F0 instead.
const double dielectricF0 = 0.04;

/// `shaders/lib/shading_constants.glsl` as `tool/gen_shading_constants.dart`
/// writes it from the constants above, and as `test/shading_constants_test`
/// holds the file on disk to.
String shadingConstantsGlsl() =>
    '''
// Generated by tool/gen_shading_constants.dart from
// lib/src/shading_constants.dart. Do not edit: change the Dart constant and
// run the generator, and the software backend and these stages move together.
//
// Included after a `precision highp float` (a stage's own, or the one
// `lib/color.glsl` states), which a constant declared in a GLSL ES fragment
// stage needs before it.

#ifndef SHADING_CONSTANTS_GLSL_
#define SHADING_CONSTANTS_GLSL_

// A dielectric's reflectance at normal incidence: ((n - 1) / (n + 1))^2 at
// n = 1.5, glTF's index for every non-metal. See `dielectricF0`.
const float kDielectricF0 = ${_glsl(dielectricF0)};

#endif  // SHADING_CONSTANTS_GLSL_
''';

/// [value] as a GLSL float literal: always with a decimal point, since
/// GLSL ES reads `1` as an int and refuses it where a float is wanted.
String _glsl(double value) {
  final text = value.toString();
  return text.contains('.') || text.contains('e') ? text : '$text.0';
}
