/// The shader ABI as text: what `api/flutter3d_shaders.abi` holds, so a
/// minor that drops or moves any of it is caught by a rule rather than by a
/// plugin bundle built against 1.0 reading the wrong offsets.
///
/// **One fact a line**, each line whole on its own (`stage Pbr block FogInfo
/// member eye 16 16 1 Vector4`), so "only grows" is a line-by-line question:
/// every line of the recorded base must still be here. A dropped entry
/// point, a removed or reordered member, a block whose offset moved, a
/// vertex input renumbered, a varying inserted before another, a sampler
/// turned from a 2D texture into a cube: each is a line of the base that is
/// gone.
///
/// The lines, by their first words:
///
/// - `entry` names an entry point of the bundle and its kind;
/// - `stage … block` names a block a compiled stage keeps, and `stage …
///   block … member` one member with its offset, byte length, elements and
///   type, as std140 lays it out;
/// - `stage … sampler` names a sampler it keeps, with the GLSL type it is
///   declared as (`sampler2D`, `samplerCube`);
/// - `vertex … in` is an engine vertex stage's attribute, by its index in
///   declaration order, and `vertex … format` the `VertexFormat` the
///   engine's vertex buffer carries it in;
/// - `vertex … out` and `fragment … in` are the varyings, in declaration
///   order, which is their location where the source states none, and
///   `fragment … out` a fragment stage's colour outputs.
///
/// A tool, not the package's API: `tool/abi_snapshot.dart` writes the file
/// from it, `test/shader_abi_test.dart` holds the committed file to it, and
/// `tool/structure` holds the file to the base recorded from the rc.1 tag.
library;

import 'dart:convert';
import 'dart:io';

import 'package:flutter3d_shaders/backend.dart'
    show StageInterface, StageVariable, stageBindings, uniformBlocks;
import 'package:flutter3d_shaders/flutter3d_shaders.dart'
    show computeShaders, requiredShaders;
import 'package:flutter3d_shaders/translate.dart' show resolveIncludes;

/// The file's first lines: what it is and how it is checked.
const String shaderAbiHeader =
    '# The shader ABI of flutter3d_shaders, one fact a line. Generated by\n'
    '# `dart run tool/abi_snapshot.dart`; a minor may add lines, never drop\n'
    '# or change one (the rule `the shader ABI only grows`).';

/// The shader ABI of the package at [packageRoot]: its entry points, each
/// compiled stage's blocks (members with offset, byte length, elements and
/// type) and samplers with their kinds, each engine vertex stage's inputs in
/// order with their formats, and each stage's varyings.
String shaderAbiSnapshot(String packageRoot) {
  final stages = _engineStages(packageRoot);
  final lines = <String>[
    for (final shader in requiredShaders)
      'entry ${shader.name} ${shader.kind.name}',
    for (final name in computeShaders) 'entry $name compute',
    for (final MapEntry(key: stage, value: bindings) in stageBindings.entries)
      for (final block in bindings.blocks) 'stage $stage block $block',
    for (final MapEntry(key: stage, value: bindings) in stageBindings.entries)
      for (final sampler in bindings.samplers)
        'stage $stage sampler $sampler ${_samplerKind(stages, stage, sampler)}',
    for (final MapEntry(key: stage, value: blocks) in uniformBlocks.entries)
      for (final MapEntry(key: block, value: members) in blocks.entries)
        for (final MapEntry(key: member, value: layout) in members.entries)
          <Object>[
            'stage $stage block $block member $member',
            layout.offset,
            layout.byteLength,
            layout.elements,
            layout.type,
          ].join(' '),
    for (final MapEntry(key: stage, value: source) in stages.entries)
      ..._variables(stage, source),
  ]..sort();
  return '$shaderAbiHeader\n${lines.join('\n')}\n';
}

/// One engine stage of the manifest, with its `#include`s resolved.
typedef _Stage = ({bool fragment, String resolved});

/// Every stage `shaders/flutter3d.shaderbundle.json` lists, by name.
Map<String, _Stage> _engineStages(String packageRoot) {
  final shaders = Directory('$packageRoot/shaders');
  final sources = <String, String>{
    for (final file in shaders.listSync(recursive: true).whereType<File>())
      if (file.path.endsWith('.glsl') ||
          file.path.endsWith('.frag') ||
          file.path.endsWith('.vert'))
        file.path.substring(shaders.path.length + 1): file.readAsStringSync(),
  };
  final manifest =
      jsonDecode(
            File(
              '${shaders.path}/flutter3d.shaderbundle.json',
            ).readAsStringSync(),
          )
          as Map<String, Object?>;
  return <String, _Stage>{
    for (final MapEntry(key: stage, value: entry) in manifest.entries)
      if (entry case {'type': final String type, 'file': final String file})
        stage: (
          fragment: type == 'fragment',
          resolved: _preprocessed(
            _withoutComments(
              resolveIncludes(
                sources[file.replaceFirst('shaders/', '')]!,
                sources,
                from: file,
              ),
            ),
          ),
        ),
  };
}

/// [source] with its `#ifdef`, `#ifndef` and `#else` branches taken as a
/// compiler for no particular target takes them: what the stage itself
/// `#define`s is defined, no `IMPELLER_TARGET_*` is. The ABI is the one
/// every target shares; an attribute only Impeller's OpenGL ES target
/// declares (`f3d_vertex_index`) is that backend's own.
String _preprocessed(String source) {
  final defined = <String>{};
  // One entry an open conditional: whether its branch is being kept.
  final open = <bool>[];
  bool keeping() => open.every((bool keep) => keep);
  final out = StringBuffer();
  for (final line in source.split('\n')) {
    final directive = RegExp(
      r'^\s*#\s*(ifdef|ifndef|else|endif|define)\b\s*(\w*)',
    ).firstMatch(line);
    switch (directive?.group(1)) {
      case 'ifdef':
        open.add(defined.contains(directive!.group(2)));
      case 'ifndef':
        open.add(!defined.contains(directive!.group(2)));
      case 'else':
        open.add(!open.removeLast());
      case 'endif':
        open.removeLast();
      case 'define' when keeping():
        defined.add(directive!.group(2)!);
      case _ when keeping():
        out.writeln(line);
    }
  }
  return out.toString();
}

/// The lines of one stage's edges: a vertex stage's attributes with their
/// formats and its varyings, a fragment stage's varyings and outputs.
List<String> _variables(String stage, _Stage source) {
  final edges = StageInterface.fromGlsl(
    source.resolved,
    name: stage,
    fragment: source.fragment,
  );
  final side = source.fragment ? 'fragment' : 'vertex';
  String line(String direction, int index, StageVariable variable) =>
      '$side $stage $direction $index ${variable.type} ${variable.name}';
  return <String>[
    for (final (index, input) in edges.inputs.indexed) ...<String>[
      line('in', index, input),
      if (!source.fragment)
        'vertex $stage format $index ${input.name} ${_format(input)}',
    ],
    for (final (index, output) in edges.outputs.indexed)
      line('out', index, output),
  ];
}

/// The `VertexFormat` the engine's vertex buffer carries [input] in: 32-bit
/// components of the input's width, floats for a float vector.
String _format(StageVariable input) {
  final shape = RegExp(r'^([iu]?)vec([234])$').firstMatch(input.type);
  final (kind, width) = switch (input.type) {
    'float' => ('float', 1),
    'int' => ('sint', 1),
    'uint' => ('uint', 1),
    _ when shape != null => (
      switch (shape.group(1)) {
        'i' => 'sint',
        'u' => 'uint',
        _ => 'float',
      },
      int.parse(shape.group(2)!),
    ),
    _ => throw StateError(
      '${input.name} is a ${input.type}, which no vertex format carries',
    ),
  };
  return width == 1 ? '${kind}32' : '${kind}32x$width';
}

/// The GLSL type [stage]'s source declares [sampler] as.
String _samplerKind(Map<String, _Stage> stages, String stage, String sampler) {
  final source =
      stages[stage]?.resolved ??
      (throw StateError('$stage keeps samplers and is not in the manifest'));
  final kinds = <String>{
    for (final match in RegExp(
      r'^\s*(?:layout\s*\([^)]*\)\s*)?uniform\s+(?:(?:highp|mediump|lowp)\s+)?'
      '(\\w+)\\s+$sampler\\s*;',
      multiLine: true,
    ).allMatches(source))
      match.group(1)!,
  };
  if (kinds.length != 1) {
    throw StateError(
      '$stage declares $sampler as ${kinds.isEmpty ? 'nothing' : kinds}',
    );
  }
  return kinds.single;
}

String _withoutComments(String source) => source
    .replaceAll(RegExp(r'/\*.*?\*/', dotAll: true), '')
    .split('\n')
    .map((String line) {
      final at = line.indexOf('//');
      return at < 0 ? line : line.substring(0, at);
    })
    .join('\n');

/// The lines of [base] that [current] no longer has: each one something a
/// minor dropped or changed. Comment lines are not facts.
List<String> shaderAbiLost({required String base, required String current}) {
  final have = <String>{...current.split('\n')};
  return <String>[
    for (final line in base.split('\n'))
      if (line.isNotEmpty && !line.startsWith('#') && !have.contains(line))
        line,
  ];
}
