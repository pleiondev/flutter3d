void main() {
  _linkTests();
  _atlasTests();

  for (final which in ParityScene.values) {
    test(
      'WebGL draws ${which.name} the way Impeller does',
      () async {
        final device = WebGlDevice.create(
          width: kParityWidth,
          height: kParityHeight,
          sources: engineShaders,
        );
        if (device == null) fail('no WebGL2 context in this browser');
        // Reported once per fixture, because it is the difference between
        // shadows and no shadows and nothing else says so.
        // ignore: avoid_print
        print('float-linear filtering: ${device.supportsFloatLinearFiltering}');

        TextureHandle texel(List<int> rgba) => device.createTextureFromPixels(
          width: 1,
          height: 1,
          format: TextureFormat.r8g8b8a8UNormInt,
          pixels: ByteData.sublistView(Uint8List.fromList(rgba)),
        )!;

        final renderer = Renderer.create(
          device: device,
          fallbackAlbedo: texel(<int>[255, 255, 255, 255]),
          fallbackNormal: texel(<int>[128, 128, 255, 255]),
        );

        final built = buildParityScene(device, which: which);
        final result = renderer.render(
          width: kParityWidth,
          height: kParityHeight,
          scene: built.scene,
          views: <RenderView>[RenderView(camera: built.camera)],
          settings: paritySettingsFor(which),
        );

        // Draw calls, because a black atlas and a pass that never ran look the
        // same in the picture and different here.
        // ignore: avoid_print
        print(
          '${which.name}: ${result.drawCalls} draws, '
          '${result.pipelines} pipelines',
        );

        final pixels = await device.readPixels(result.frame);
        expect(pixels, isNotNull, reason: 'the frame could not be read back');

        final mine = parityGrid(
          pixels!.buffer.asUint8List(),
          kParityWidth,
          kParityHeight,
        );
        // The WebGL grid itself, not only the difference. A uniformly zero frame
        // and a lit scene shown where an atlas should be are the same number
        // against a white reference and different pictures.
        if (which == ParityScene.pointShadow ||
            which == ParityScene.sky ||
            which == ParityScene.pointShadowMap) {
          // ignore: avoid_print
          print(
            '${which.name} webgl rows 0,7,15: '
            '${mine.sublist(0, 8)} | '
            '${mine.sublist(7 * kParityGrid, 7 * kParityGrid + 8)} | '
            '${mine.sublist(15 * kParityGrid, 15 * kParityGrid + 8)}',
          );
        }

        final reference0 = kImpellerGrids[which]!;
        if (which == ParityScene.pointShadowMap) {
          // How much of the atlas is *not* the clear colour. A map that cleared
          // and never drew is uniformly white, and against a reference whose
          // occluders are small that still averages close at this resolution.
          int dark(List<int> g) => g.where((v) => v < 200).length;
          // ignore: avoid_print
          print(
            'atlas cells below 200 — webgl ${dark(mine)}, '
            'impeller ${dark(reference0)}',
          );
        }
        final reference = reference0;
        expect(mine.length, reference.length);

        var worst = 0;
        var worstAt = -1;
        var total = 0;
        for (var i = 0; i < mine.length; i++) {
          final delta = (mine[i] - reference[i]).abs();
          total += delta;
          if (delta > worst) {
            worst = delta;
            worstAt = i;
          }
        }
        final mean = total / mine.length;

        // Printed whether it passes or not. A comparison whose number nobody sees
        // is a threshold nobody can judge, which is how two goldens sat under one
        // for a fortnight in this project.
        // ignore: avoid_print
        print(
          'parity ${which.name}: mean ${mean.toStringAsFixed(2)}, '
          'worst $worst at cell ${worstAt ~/ kParityGrid},'
          '${worstAt % kParityGrid}',
        );

        // Eight and one, against 3 and 0.04 measured on the plain fixture. Room
        // for a driver that rounds differently, none for a shape in the wrong
        // place — the lesson of two goldens that sat at 0.178% under a 0.2% limit
        // for two commits is that a limit far above the observed value has
        // stopped watching.
        expect(
          worst,
          lessThan(8),
          reason:
              'cell ${worstAt ~/ kParityGrid},${worstAt % kParityGrid} '
              'differs by $worst: WebGL ${worstAt < 0 ? '-' : mine[worstAt]}, '
              'Impeller ${worstAt < 0 ? '-' : reference[worstAt]}',
        );
        expect(
          mean,
          lessThan(1.0),
          reason:
              'the two backends disagree across the whole frame, '
              'not in one place',
        );
      },
      // **This fixture was skipped for six sessions and is not skipped now.**
      // What it was: the lit floor came back lit where Impeller has it dark,
      // mean 7.95 against a budget of 8, while the atlas the lookup reads
      // compared *exactly* equal on both backends across six scenes. It is
      // 0.04 now, and the one line that did it is in `PointShadowDistance`.
      //
      // The cube atlas is stored bottom-up on this backend, and both halves
      // of its address were wrong. A light in slot zero is drawn into the row
      // the shader would call three, because the tile's viewport rectangle is
      // flipped to land it there; and the picture inside that tile is
      // upside down as well, because it was drawn through a projection built
      // for the other origin. Turning the whole atlas over in the lookup —
      // `atlas.y = 1.0 - atlas.y`, behind `params3.x`, which the device
      // answers — fixes the row and the tile together, because a whole-texture
      // flip is exactly "row `n` becomes row `slots - 1 - n`, and `v` becomes
      // `1 - v`".
      //
      // **Why every check of the atlas passed while the lookup failed**, and
      // this is the part worth carrying to the next backend: the views that
      // composite the atlas — `pointShadowMap`, `cube-shadow` and its two
      // neighbours — put it through a full-screen pass, and a full-screen
      // pass on a bottom-left backend turns its input over. The picture came
      // back the right way up and matched Impeller to the pixel. The lit pass
      // samples the same texture directly and has no such pass to cancel, so
      // it read a row that had never been drawn into and found nothing in the
      // way of anything. An instrument that cancels the error it is pointed
      // at agrees with everything.
      //
      // Refuted along the way, so nobody walks the circle again:
      // OES_texture_float_linear, std140 array stride, stage linking, the
      // atlas texture's size, a silently dropped uniform member, the shadow
      // strength, the face matrices through `toFramebufferOrigin`, and the
      // static atlas in the `min`. Two real causes were found and fixed
      // before this one: GL measures a viewport from the bottom, so the
      // occupied row went to the wrong end of the texture, and a clear
      // respects the scissor here where the contract says it covers the whole
      // attachment.
      //
      // Two of those refutations were not measurements at all, and that cost
      // the most. The reading they rested on — this backend finding a blocker
      // at 0.07 of the light's range where the software backend finds one at
      // 0.86 — compared two different quantities twice over. The software
      // backend's point-shadow shading is a separate Dart implementation and
      // does not read the debug flag, so one side was a debug picture and the
      // other an ordinary frame; and on this side the number was `blockerOut`
      // still holding its `-1` sentinel, clamped into green as a zero,
      // because `PointShadowPenumbra` returns before it searches when the
      // light has no radius. Zero there now means a distance that was really
      // measured — see the early return in that function.
    );
  }
}

/// Whether the cube shadow atlas can exist here at all.
///
/// Six tiles across and one row per shadowed light, so at the default tile size
/// it is 6144 by 4096 — wide enough to be worth asking about, and a texture
/// that cannot be created is a shadow pass that cannot run.
void _atlasTests() {
  test('the cube shadow atlas is a texture this backend can make', () {
    final device = WebGlDevice.create(
      width: 64,
      height: 64,
      sources: engineShaders,
    );
    if (device == null) fail('no WebGL2 context in this browser');
    final atlas = device.createTexture(
      const RenderTargetSpec(
        width: 6144,
        height: 4096,
        format: TextureFormat.r16g16b16a16Float,
      ),
    );
    // ignore: avoid_print
    print('atlas 6144x4096: ${atlas.width}x${atlas.height}');
    expect(atlas.width, 6144);
  });
}

/// Every stage pair the engine links, linked here.
///
/// A shader that compiles is not a shader that links. GLSL ES matches a
/// fragment stage's inputs against the vertex stage's outputs, and a mismatch
/// is a link error — where Impeller drops an input nothing reads and links
/// anyway. The pairs below are the ones the renderer builds, so a mismatch in
/// any of them is a pass that cannot run.
void _linkTests() {
  // **Every pair, because the list used to be a subset and that is how a
  // broken one hid.** Nine of these were checked and the rest were not: four of
  // the six lighting models, both sky stages, the skinned vertex stage and both
  // mesh-particle stages went unlinked here from the day this file was written.
  // `lighting-unlit` draws an empty frame on this backend, and nothing between
  // the shader and the golden set was in a position to say so.
  const pairs = <(String, String)>[
    ('MeshVertex', 'Unlit'),
    ('MeshVertex', 'Lambert'),
    ('MeshVertex', 'BlinnPhong'),
    ('MeshVertex', 'Pbr'),
    ('MeshVertex', 'Toon'),
    ('MeshVertex', 'Normals'),
    ('MeshVertex', 'ShadowDepth'),
    ('MeshVertex', 'ShadowDistance'),
    // The skinned stage draws the same models from a second vertex layout, so
    // every one of them is a pair here too.
    ('MeshSkinnedVertex', 'Unlit'),
    ('MeshSkinnedVertex', 'Lambert'),
    ('MeshSkinnedVertex', 'BlinnPhong'),
    ('MeshSkinnedVertex', 'Pbr'),
    ('MeshSkinnedVertex', 'Toon'),
    ('MeshSkinnedVertex', 'Normals'),
    ('MeshSkinnedVertex', 'ShadowDepth'),
    ('MeshSkinnedVertex', 'ShadowDistance'),
    ('ShadowTileResetVertex', 'ShadowTileReset'),
    ('FullscreenVertex', 'Composite'),
    ('FullscreenVertex', 'BloomThreshold'),
    ('FullscreenVertex', 'BloomDownsample'),
    ('FullscreenVertex', 'BloomUpsample'),
    ('FullscreenVertex', 'Reflections'),
    ('FullscreenVertex', 'Ssao'),
    ('DebugLineVertex', 'DebugLine'),
    ('ParticleVertex', 'Particle'),
    ('ParticleVertex', 'ParticleTextured'),
    ('ParticleMeshVertex', 'ParticleMesh'),
    ('SkyVertex', 'Sky'),
    ('SkyCubeVertex', 'SkyCube'),
  ];

  for (final (vertex, fragment) in pairs) {
    test('$vertex + $fragment links', () {
      final device = WebGlDevice.create(
        width: 64,
        height: 64,
        sources: engineShaders,
      );
      if (device == null) fail('no WebGL2 context in this browser');
      final v = device.shaders[vertex];
      final f = device.shaders[fragment];
      expect(v, isNotNull, reason: '$vertex did not compile');
      expect(f, isNotNull, reason: '$fragment did not compile');
      expect(() => device.createPipeline(v!, f!), returnsNormally);
    });
  }
}
